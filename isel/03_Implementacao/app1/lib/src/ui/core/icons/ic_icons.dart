    canvas.scale(scale);
    final paint = Paint()
      ..style = PaintingStyle.stroke
      ..strokeWidth = 2
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round
      ..color = color
      ..isAntiAlias = true;
    canvas.drawPath(path, paint);
  }

  @override
  bool shouldRepaint(_IconPainter oldDelegate) => oldDelegate.path != path || oldDelegate.color != color;
}

/// Minimal parser for the absolute SVG commands Figma emits for this icon
/// set (M, L, H, V, C, Z). Throws on anything else so a future icon with a
/// relative/arc command fails loudly in tests instead of drawing garbage.
Path parseSvgPathData(String d) {
  final path = Path();
  final tokens = RegExp(r'[MLHVCZmlhvcz]|-?\d*\.?\d+(?:e-?\d+)?').allMatches(d).map((m) => m.group(0)!).toList();
  var i = 0;
  var cmd = '';
  double x = 0, y = 0;
  double next() => double.parse(tokens[i++]);
  bool isCommand(String t) => RegExp(r'^[A-Za-z]$').hasMatch(t);
  while (i < tokens.length) {
    if (isCommand(tokens[i])) cmd = tokens[i++];
    switch (cmd) {
      case 'M':
        x = next();
        y = next();
        path.moveTo(x, y);
        cmd = 'L'; // subsequent pairs are implicit line-tos
      case 'L':
        x = next();
        y = next();
        path.lineTo(x, y);
      case 'H':
        x = next();
        path.lineTo(x, y);
      case 'V':
        y = next();
        path.lineTo(x, y);
      case 'C':
        final x1 = next(), y1 = next(), x2 = next(), y2 = next();
        x = next();
        y = next();
        path.cubicTo(x1, y1, x2, y2, x, y);
      case 'Z':
        path.close();
        cmd = ''; // numbers straight after Z are malformed → default throws
      default:
        throw FormatException('Unsupported SVG path command "$cmd" in icon data');
    }
  }
  return path;
}
